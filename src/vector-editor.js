/**
 * Deterministic, entirely local post-trace SVG cleanup.
 * Accepts only the restricted path-only SVG emitted by Chomp's own editable
 * tracer. It never parses arbitrary uploaded SVGs or inserts SVG markup as HTML.
 */
const SVG_ROOT = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="(\d+)" height="(\d+)" viewBox="0 0 (\d+) (\d+)">([\s\S]*)<\/svg>$/;
const SVG_PATH = /<path data-chomp-shape="(s\d+)" fill="(#[\da-fA-F]{6})"(?: fill-opacity="(0?\.\d+|1(?:\.0+)?)")? fill-rule="evenodd" d="([^"]+)"\/>/g;
const VALID_PATH = /^[MmLlCcHhVvZz0-9+.,\-\seE]+$/;
const VALID_COLOR = /^#[a-fA-F0-9]{6}$/;

export function openVectorDocument(svgText) {
  if (typeof svgText !== 'string' || svgText.length > 12_000_000)
    throw new Error('Invalid editable vector data.');
  const root = svgText.match(SVG_ROOT);
  if (!root) throw new Error('This SVG was not generated by the Chomp shape editor.');
  const [, widthText, heightText, boxWidthText, boxHeightText, contents] = root;
  const width = Number(widthText), height = Number(heightText);
  const boxWidth = Number(boxWidthText), boxHeight = Number(boxHeightText);
  if (![width, height, boxWidth, boxHeight].every(n => Number.isSafeInteger(n) && n > 0 && n <= 32768))
    throw new Error('Invalid SVG dimensions.');
  const shapes = [];
  for (const match of contents.matchAll(SVG_PATH)) {
    const [raw, id, fill, opacity, d] = match;
    if (id !== 's' + shapes.length || !VALID_PATH.test(d))
      throw new Error('Invalid editable SVG path.');
    const alpha = opacity === undefined ? null : Number(opacity);
    if (alpha !== null && (!Number.isFinite(alpha) || alpha < 0 || alpha > 1))
      throw new Error('Invalid shape opacity.');
    shapes.push({ id, fill: fill.toLowerCase(), opacity: alpha, d, hidden: false });
    if (shapes.length > 4096) throw new Error('Too many shapes to edit.');
    if (!raw.length) throw new Error('Invalid SVG path.');
  }
  if (contents.replace(SVG_PATH, '') !== '') throw new Error('Unexpected SVG content.');
  return {
    width, height, boxWidth, boxHeight, shapes,
    baseline: shapes.map(s => ({ fill: s.fill, hidden: false })),
    undoStack: [], redoStack: []
  };
}

function findShape(doc, id) {
  const shape = doc?.shapes?.find(shape => shape.id === id);
  if (!shape) throw new Error('Unknown vector shape.');
  return shape;
}

export function modifyVectorShape(doc, id, changes) {
  const shape = findShape(doc, id);
  const fill = changes && changes.fill !== undefined ? changes.fill : shape.fill;
  const hidden = changes && changes.hidden !== undefined ? changes.hidden : shape.hidden;
  if (typeof fill !== 'string' || !VALID_COLOR.test(fill) || typeof hidden !== 'boolean')
    throw new Error('Invalid shape edit.');
  const next = { fill: fill.toLowerCase(), hidden };
  const previous = { fill: shape.fill, hidden: shape.hidden };
  if (next.fill === previous.fill && next.hidden === previous.hidden) return false;
  Object.assign(shape, next);
  doc.undoStack.push({ id, previous, next });
  if (doc.undoStack.length > 100) doc.undoStack.shift();
  doc.redoStack = [];
  return true;
}

export function undoVectorEdit(doc) {
  const action = doc.undoStack.pop();
  if (!action) return false;
  Object.assign(findShape(doc, action.id), action.previous);
  doc.redoStack.push(action);
  return true;
}

export function redoVectorEdit(doc) {
  const action = doc.redoStack.pop();
  if (!action) return false;
  Object.assign(findShape(doc, action.id), action.next);
  doc.undoStack.push(action);
  return true;
}

export function resetVectorEdits(doc) {
  doc.shapes.forEach((shape, i) => Object.assign(shape, doc.baseline[i]));
  doc.undoStack = []; doc.redoStack = [];
}

export function hasVectorEdits(doc) {
  return doc.shapes.some((shape, i) =>
    shape.fill !== doc.baseline[i].fill || shape.hidden !== doc.baseline[i].hidden);
}

export function serializeVectorDocument(doc) {
  if (!doc || !Array.isArray(doc.shapes)) throw new Error('Invalid vector document.');
  let svg = '<svg xmlns="http://www.w3.org/2000/svg" width="' + doc.width +
    '" height="' + doc.height + '" viewBox="0 0 ' + doc.boxWidth + ' ' + doc.boxHeight + '">';
  for (const shape of doc.shapes) {
    if (shape.hidden) continue;
    // Data is validated when read and every subsequent mutation is validated.
    svg += '<path data-chomp-shape="' + shape.id + '" fill="' + shape.fill + '"' +
      (shape.opacity === null ? '' : ' fill-opacity="' + shape.opacity.toFixed(3) + '"') +
      ' fill-rule="evenodd" d="' + shape.d + '"/>';
  }
  return svg + '</svg>';
}
